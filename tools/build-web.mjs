// Builds the phone setup page that the card serves:
//  web/index.html + vendored libs (omggif, gifenc: MIT; jpeg-js encoder: BSD) -> one self-contained page,
//  gzipped into firmware/pocket_jumbotron/web_index.h (built-in copy at /local) and copied to docs/app/ (the
//  website copy that the card's front page loads). Also writes firmware/build/web/index.html for testing.
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, '..');
const nm = path.join(here, 'node_modules');

const omggif = fs.readFileSync(path.join(nm, 'omggif/omggif.js'), 'utf8');
let gifenc = fs.readFileSync(path.join(nm, 'gifenc/dist/gifenc.esm.js'), 'utf8').replace(/\/\/# sourceMappingURL.*$/m, '');
gifenc = gifenc.replace(/export\{([^}]*)\};?/, (_, list) => {
  const pairs = list.split(',').map(s => s.trim().split(/\s+as\s+/)).map(([local, name]) => `${name || local}:${local}`);
  return `window.gifenc={${pairs.join(',')}};`;
});
// jpeg-js encoder: 4:4:4 JPEGs (full color resolution; the browser's own JPEGs halve it and smear reds/greens).
const jpegjs = fs.readFileSync(path.join(nm, 'jpeg-js/lib/encoder.js'), 'utf8');
const convert = fs.readFileSync(path.join(root, 'web/convert.js'), 'utf8');   // decoding/encoding pictures
const pjfont = fs.readFileSync(path.join(root, 'web/pjfont.js'), 'utf8');   // our font: same pixels as the card
const wxicons = fs.readFileSync(path.join(root, 'web/wxicons.js'), 'utf8');   // weather icon sprites (tools/make-wxicons.mjs)
const fxsprites = fs.readFileSync(path.join(root, 'web/fxsprites.js'), 'utf8');   // effect sprites (tools/make-fxsprites.mjs)
const vendor = `<script>/* omggif (MIT) */${omggif}</script>\n<script>/* gifenc (MIT, Matt DesLauriers) */(function(){${gifenc}})();</script>\n<script>/* jpeg-js encoder (BSD, Adobe / Andreas Ritter) */(function(){var module;${jpegjs}})();</script>
<script>${convert}</script>
<script>${pjfont}</script>\n<script>${wxicons}</script>\n<script>${fxsprites}</script>`;

// Build stamp shown on the page ("app 2026-11-20 abc1234"); the website copy is what cards normally run.
let rev = ''; try { rev = (await import('node:child_process')).execSync('git rev-parse --short HEAD', { cwd: root }).toString().trim(); } catch (e) {}
const stamp = new Date().toISOString().slice(0, 10) + (rev ? ' ' + rev : '');
// The app's own code: web/app/*.js joined in name order into one script (one shared scope, as if one file).
const appDir = path.join(root, 'web/app');
const app = fs.readdirSync(appDir).filter(f => f.endsWith('.js')).sort().map(f => fs.readFileSync(path.join(appDir, f), 'utf8')).join('\n');
const html = fs.readFileSync(path.join(root, 'web/index.html'), 'utf8').replace('<!--VENDOR-->', () => vendor)
  .replace('<!--APP-->', () => `<script>\n${app}</script>`).replace('/*APP_BUILD*/', stamp);
const outDir = path.join(root, 'firmware/build/web');
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'index.html'), html);
// The website copy the card's starter page loads (published by CI from docs/app/, not committed).
fs.mkdirSync(path.join(root, 'docs/app'), { recursive: true });
fs.writeFileSync(path.join(root, 'docs/app/index.html'), html);
// The pack builder's hosted copy (docs/builder/): the same page tools/pack-builder.mjs serves on this PC, with the
// picture libraries inlined; on the website it edits the private content repo through the GitHub API.
const builderVendor = `<script>${omggif}</script>
<script>(function(){${gifenc}})();</script>
<script>(function(){var module;${jpegjs}})();</script>
<script>${convert}</script>`;
fs.mkdirSync(path.join(root, 'docs/builder'), { recursive: true });
fs.writeFileSync(path.join(root, 'docs/builder/index.html'), fs.readFileSync(path.join(here, 'pack-builder.html'), 'utf8').replace('<!--VENDOR-->', () => builderVendor));

const toC = (name, text) => {
  const gz = zlib.gzipSync(text, { level: 9 });
  let hex = '';
  for (let i = 0; i < gz.length; i++) hex += (i % 20 === 0 ? '\n  ' : '') + '0x' + gz[i].toString(16).padStart(2, '0') + ',';
  console.log(`${name}: ${(text.length / 1024).toFixed(1)} KB -> gzip ${(gz.length / 1024).toFixed(1)} KB`);
  return `static const uint8_t ${name}[] = {${hex}
};
static const size_t ${name}_LEN = sizeof(${name});
`;
};
const wifi = fs.readFileSync(path.join(root, 'web/wifi.html'), 'utf8');
fs.writeFileSync(path.join(outDir, 'wifi.html'), wifi);
const header = `// Generated by tools/build-web.mjs from web/*.html - do not edit.
#pragma once
#include <stdint.h>
#include <stddef.h>
${toC('WEB_INDEX_GZ', html)}${toC('WEB_WIFI_GZ', wifi)}`;
fs.writeFileSync(path.join(root, 'firmware/pocket_jumbotron/web_index.h'), header);
