// Builds the phone setup page that the card serves:
//  web/index.html + vendored libs (omggif, gifenc, aes-js, js-sha256; MIT) + web/vault.js -> one self-contained page,
//  gzipped into firmware/pocket_jumbotron/web_index.h. Also writes firmware/build/web/index.html for testing.
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, '..');
const nm = path.join(here, 'node_modules');

const omggif = fs.readFileSync(path.join(nm, 'omggif/omggif.js'), 'utf8');
let gifenc = fs.readFileSync(path.join(nm, 'gifenc/dist/gifenc.esm.js'), 'utf8').replace(/\/\/# sourceMappingURL.*$/m, '');
gifenc = gifenc.replace(/export\{([^}]*)\};?/, (_, list) => {
  const pairs = list.split(',').map(s => s.trim().split(/\s+as\s+/)).map(([local, name]) => `${name || local}:${local}`);
  return `window.gifenc={${pairs.join(',')}};`;
});
const aesjs = fs.readFileSync(path.join(nm, 'aes-js/index.js'), 'utf8');
const sha256 = fs.readFileSync(path.join(nm, 'js-sha256/src/sha256.js'), 'utf8');
const vaultJs = fs.readFileSync(path.join(root, 'web/vault.js'), 'utf8');
const vendor = `<script>/* aes-js (MIT, Richard Moore) */${aesjs}</script>
<script>/* js-sha256 (MIT, Chen Yi-Cyuan) */${sha256}</script>
<script>${vaultJs}</script>
<script>/* omggif (MIT) */${omggif}</script>\n<script>/* gifenc (MIT, Matt DesLauriers) */(function(){${gifenc}})();</script>`;

const html = fs.readFileSync(path.join(root, 'web/index.html'), 'utf8').replace('<!--VENDOR-->', vendor);
const outDir = path.join(root, 'firmware/build/web');
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'index.html'), html);

const toC = (name, text) => {
  const gz = zlib.gzipSync(text, { level: 9 });
  let hex = '';
  for (let i = 0; i < gz.length; i++) hex += (i % 20 === 0 ? '\n  ' : '') + '0x' + gz[i].toString(16).padStart(2, '0') + ',';
  console.log(`${name}: ${(text.length / 1024).toFixed(1)} KB -> gzip ${(gz.length / 1024).toFixed(1)} KB`);
  return `static const uint8_t ${name}[] = {${hex}
};
static const size_t ${name}_LEN = sizeof(${name});
`;
};
const wifi = fs.readFileSync(path.join(root, 'web/wifi.html'), 'utf8');
fs.writeFileSync(path.join(outDir, 'wifi.html'), wifi);
const header = `// Generated by tools/build-web.mjs from web/*.html - do not edit.
#pragma once
#include <stdint.h>
#include <stddef.h>
${toC('WEB_INDEX_GZ', html)}${toC('WEB_WIFI_GZ', wifi)}`;
fs.writeFileSync(path.join(root, 'firmware/pocket_jumbotron/web_index.h'), header);
