// Renders our PJ font (web/pjfont.js) into firmware/pocket_jumbotron/pj_font.h (4-bit alpha bitmaps).
//   node tools/make-pjfont.mjs [preview.png]   also writes a panel-sized preview picture (scaled up) when given.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const ctx = {}; vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root, 'web/pjfont.js'), 'utf8'), ctx);
const PJ = ctx.PJFont;

let h = `// Generated by tools/make-pjfont.mjs from web/pjfont.js - do not edit.
// Our own font: per size, glyphs ${PJ.FIRST}..${PJ.LAST} (127 = degree sign), 4-bit alpha, two pixels per byte.
#pragma once
#include <stdint.h>
struct PJGlyph { uint32_t off; uint8_t w, h; int8_t dx, dy; uint8_t adv; };
struct PJFontDef { const uint8_t *bits; const PJGlyph *g; uint8_t cap, weight, gap; };
`;
let total = 0;
const names = [];
for (const n of Object.keys(PJ.SIZES)) {
  const f = PJ.all(+n);
  const bytes = [], gl = [];
  for (const g of f.g) {
    const off = bytes.length;
    for (let i = 0; i < g.a.length; i += 2) bytes.push(g.a[i] << 4 | (g.a[i + 1] ?? 0));
    gl.push(`{${off},${g.w},${g.h},${g.dx},${g.dy},${g.adv}}`);
  }
  total += bytes.length + gl.length * 10;
  let hex = '';
  for (let i = 0; i < bytes.length; i++) hex += (i % 24 === 0 ? '\n  ' : '') + '0x' + bytes[i].toString(16).padStart(2, '0') + ',';
  h += `static const uint8_t PJ${n}_BITS[] = {${hex}\n};\nstatic const PJGlyph PJ${n}_G[] = {${gl.join(',')}};\n`;
  names.push(`{PJ${n}_BITS, PJ${n}_G, ${f.cap}, ${f.w}, ${f.gap}}`);
}
h += `static const PJFontDef PJ_FONTS[] = {${names.join(', ')}};   // font numbers ${Object.keys(PJ.SIZES).join(', ')}\n`;
fs.writeFileSync(path.join(root, 'firmware/pocket_jumbotron/pj_font.h'), h);
console.log(`pj_font.h: ${(total / 1024).toFixed(1)} KB of font data`);

const out = process.argv[2];
if (out) {
  const sharp = (await import('sharp')).default;
  // Several 128x64 "screens" stacked, drawn in a soft white on black, then scaled up with dark gaps (LED look).
  const screens = [
    [[8, 'S&P 500 sinks 3.7% and the Nasdaq', 12], [8, 'WORLD NEWS: Rising seas, 1234567890', 25], [9, 'S&P 500 sinks 3.7% and', 40], [9, 'Quinault village (ja) #1', 56]],
    [[12, '12:45', 40], [9, 'FRI NOV 20', 58]],
    [[10, '57\x7f', 28], [9, 'Hello Mom!', 52]],
    [[10, 'Merry Christmas', 22], [10, 'abcdefghijklm', 42], [10, 'nopqrstuvwxyz', 60]],
    [[11, 'ABCDEFGHI', 28], [11, 'JKLMNOPQR', 58]],
    [[11, 'STUVWXYZ', 28], [11, '48,147', 58]],
  ];
  const SC = 6, w = 128, hh = 64, img = Buffer.alloc(w * SC * hh * SC * screens.length * 3);
  const rowStride = w * SC * 3;
  screens.forEach((lines, si) => {
    const buf = new Float32Array(w * hh);
    for (const [n, s, base] of lines) {
      const tw = PJ.width(n, s);
      PJ.draw(n, s, Math.max(1, Math.floor((w - tw) / 2)), base, (x, y, a) => { if (x >= 0 && y >= 0 && x < w && y < hh) buf[y * w + x] = Math.max(buf[y * w + x], a); });
    }
    for (let y = 0; y < hh; y++) for (let x = 0; x < w; x++) {
      const a = buf[y * w + x];
      for (let yy = 0; yy < SC - 1; yy++) for (let xx = 0; xx < SC - 1; xx++) {
        const o = ((si * hh + y) * SC + yy) * rowStride + (x * SC + xx) * 3;
        img[o] = 40 + a * 200; img[o + 1] = 40 + a * 190; img[o + 2] = 40 + a * 170;
      }
    }
  });
  await sharp(img, { raw: { width: w * SC, height: hh * SC * screens.length, channels: 3 } }).png().toFile(out);
  console.log('preview:', out);
}
