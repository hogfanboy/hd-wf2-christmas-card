// Turns firmware/intro.gif (the startup animation, our own art from tools/make-starter.mjs) into
// firmware/pocket_jumbotron/intro_gif.h. Run after changing the GIF: node tools/make-intro.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const gif = fs.readFileSync(path.join(root, 'firmware/intro.gif'));
let hex = '';
for (let i = 0; i < gif.length; i++) hex += (i % 20 === 0 ? '\n  ' : '') + '0x' + gif[i].toString(16).padStart(2, '0') + ',';
fs.writeFileSync(path.join(root, 'firmware/pocket_jumbotron/intro_gif.h'),
  `// Generated by tools/make-intro.mjs from firmware/intro.gif. Don't edit.\nstatic const uint8_t INTRO_GIF[] = {${hex}\n};\nstatic const size_t INTRO_GIF_LEN = sizeof(INTRO_GIF);\n`);
console.log(`intro_gif.h: ${gif.length} bytes`);
